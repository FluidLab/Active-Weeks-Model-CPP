def plot_marginal_distributions(histogram, h_edges, L_edges, save_path=None):
    """
    Plot marginal distributions for h and L.
    """
    total_counts = histogram.sum()

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))
    
   # Marginal distribution of h (sum over L)
    h_marginal = histogram.sum(axis=1)
    h_centers = (h_edges[:-1] + h_edges[1:]) / 2

    # Convert to probability density
    bin_width = h_edges[1] - h_edges[0]  # assuming uniform bins
    h_probability_density = h_marginal / (total_counts * bin_width)

    ax1.plot(h_centers, h_probability_density, 'b-', linewidth=2)
    #ax1.set_yscale('log') # Log scale
    ax1.set_xlabel(r'$h$', fontsize=14)
    ax1.set_ylabel(r'$p(h)$', fontsize=14)
    ax1.set_title(r'Marginal Distribution of $h$ (pdf)', fontsize=14)
    ax1.grid(True, alpha=0.3)
    
    # Marginal distribution of L (sum over h)
    L_marginal = histogram.sum(axis=0)
    L_centers = (L_edges[:-1] + L_edges[1:]) / 2

    # Convert to probability density
    L_bin_width = L_edges[1] - L_edges[0]  # assuming uniform bins
    L_probability_density = L_marginal / (total_counts * L_bin_width)

    ax2.plot(L_centers, L_probability_density, 'r-', linewidth=2)
    ax2.set_yscale('log')
    ax2.set_xlabel(r'$L$', fontsize=14)
    ax2.set_ylabel(r'$p(L)$', fontsize=14)
    ax2.set_title(r'Marginal Distribution of $L$ (pdf)', fontsize=14)
    ax2.grid(True, alpha=0.3)
    
    plt.tight_layout()
    
    if save_path:
        #plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"Figure saved to {save_path}")
    
    return fig, (ax1, ax2)

def plot_conditional_distribution_h_given_L(histogram, h_edges, L_edges, L_value=2.0, save_path=None):
    """
    Plot conditional distribution of h given L=L_value: p(h|L).
    """
    # Find the bin index corresponding to L_value
    L_centers = (L_edges[:-1] + L_edges[1:]) / 2
    L_bin_idx = np.argmin(np.abs(L_centers - L_value))
    actual_L = L_centers[L_bin_idx]
    
    # Extract the slice at this L value (histogram is shape (h_bins, L_bins))
    h_conditional = histogram[:, L_bin_idx]
    
    # Normalize to get conditional probability density p(h|L)
    h_centers = (h_edges[:-1] + h_edges[1:]) / 2
    h_bin_width = h_edges[1] - h_edges[0]
    
    # Conditional probability density: normalize the slice so it integrates to 1
    total_in_slice = h_conditional.sum()
    if total_in_slice > 0:
        h_conditional_density = h_conditional / (total_in_slice * h_bin_width)
    else:
        h_conditional_density = np.zeros_like(h_conditional)
        print(f"Warning: No counts found at L={actual_L:.3f}")
    
    # Plot
    fig, ax = plt.subplots(figsize=(7, 5))
    ax.plot(h_centers, h_conditional_density, 'g-', linewidth=2)
    ax.set_xlabel(r'$h$', fontsize=14)
    ax.set_ylabel(r'$p(h \mid L = {:.2f})$'.format(actual_L), fontsize=14)
    ax.set_title(r'Conditional Distribution of $h$ given $L = {:.2f}$'.format(actual_L), fontsize=14)
    ax.grid(True, alpha=0.3)
    
    # Add vertical line at h=0 if it's in range
    if h_edges[0] <= 0 <= h_edges[-1]:
        ax.axvline(0, color='k', linestyle='--', alpha=0.5, label=r'$h=0$')
        ax.legend()
    
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"Figure saved to {save_path}")
    
    return fig, ax, actual_L

def plot_conditional_with_peaks(histogram, h_edges, L_edges, L_value=2.0, 
                                prominence=0.01, distance=None, save_path=None):
    """
    Plot conditional distribution of h given L=L_value with peaks identified.
    
    Parameters
    ----------
    prominence : float
        Minimum prominence for peak detection (relative to max density)
    distance : int, optional
        Minimum number of bins between peaks
    """
    # Find the bin index corresponding to L_value
    L_centers = (L_edges[:-1] + L_edges[1:]) / 2
    L_bin_idx = np.argmin(np.abs(L_centers - L_value))
    actual_L = L_centers[L_bin_idx]
    
    # Extract and normalize the slice
    h_conditional = histogram[:, L_bin_idx]
    h_centers = (h_edges[:-1] + h_edges[1:]) / 2
    h_bin_width = h_edges[1] - h_edges[0]
    
    total_in_slice = h_conditional.sum()
    if total_in_slice > 0:
        h_conditional_density = h_conditional / (total_in_slice * h_bin_width)
    else:
        h_conditional_density = np.zeros_like(h_conditional)
        print(f"Warning: No counts found at L={actual_L:.3f}")
        return None, None, None, None
    
    # Find peaks
    # Scale prominence by maximum density for relative threshold
    abs_prominence = prominence * h_conditional_density.max()
    peaks, properties = find_peaks(h_conditional_density, 
                                   prominence=abs_prominence,
                                   distance=distance)
    
    peak_heights = h_conditional_density[peaks]
    peak_positions = h_centers[peaks]
    
    # Plot
    fig, ax = plt.subplots(figsize=(8, 6))
    ax.plot(h_centers, h_conditional_density, 'g-', linewidth=2, label='Distribution')
    
    # Mark peaks
    if len(peaks) > 0:
        ax.plot(peak_positions, peak_heights, 'ro', markersize=8, 
               label=f'Peaks (n={len(peaks)})')
        
        # Annotate peaks with their h values
        for h_pos, h_height in zip(peak_positions, peak_heights):
            ax.annotate(f'$h={h_pos:.3f}$', 
                       xy=(h_pos, h_height),
                       xytext=(10, 10), textcoords='offset points',
                       fontsize=10, 
                       bbox=dict(boxstyle='round,pad=0.3', facecolor='yellow', alpha=0.7),
                       arrowprops=dict(arrowstyle='->', connectionstyle='arc3,rad=0'))
    
    ax.set_xlabel(r'$h$', fontsize=14)
    ax.set_ylabel(r'$p(h \mid L = {:.2f})$'.format(actual_L), fontsize=14)
    ax.set_title(r'Conditional Distribution with Peaks at $L = {:.2f}$'.format(actual_L), 
                fontsize=14)
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=12)
    
    # Add vertical line at h=0
    if h_edges[0] <= 0 <= h_edges[-1]:
        ax.axvline(0, color='k', linestyle='--', alpha=0.5, linewidth=1)
    
    plt.tight_layout()
    
    # if save_path:
    #     plt.savefig(save_path, dpi=300, bbox_inches='tight')
    #     print(f"Figure saved to {save_path}")
    
    # Print peak information
    print(f"\nPeaks found at L={actual_L:.3f}:")
    print(f"{'h position':<12} {'Height':<12} {'Prominence':<12}")
    print("-" * 40)
    for i, (h_pos, height) in enumerate(zip(peak_positions, peak_heights)):
        prom = properties['prominences'][i]
        print(f"{h_pos:<12.4f} {height:<12.4e} {prom:<12.4e}")
    
    return fig, ax, peak_positions, peak_heights


def save_peak_positions(peaks, save_path):
    """
    Save peak positions to a text file in a format that can be read by the C++ 
    transition matrix calculator.
    
    Args:
        peaks: List of tuples (h_peak, L_peak, value, h_idx, L_idx)
        save_path: Path to save the peak positions file
    """
    # Sort peaks by h value (smallest to largest)
    sorted_peaks = sorted(peaks, key=lambda x: x[0])

    with open(save_path, 'w') as f:
        f.write("# h_peak  L_peak\n")
        for h_peak, L_peak, _, _, _ in sorted_peaks:
            f.write(f"{h_peak:.6f}  {L_peak:.6f}\n")
    
    print(f"\nPeak positions saved to {save_path}")
    print(f"  Number of peaks: {len(peaks)}")


def analyze_histogram(histogram, h_edges, L_edges, metadata):
    """
    Print statistical analysis of the histogram.
    """
    print("\n=== Histogram Analysis ===")
    print(f"Total counts: {metadata['total_counts']:,}")
    print(f"h range: [{metadata['h_min']:.4f}, {metadata['h_max']:.4f}]")
    print(f"L range: [{metadata['L_min']:.4f}, {metadata['L_max']:.4f}]")
    print(f"Number of bins: {metadata['n_bins_h']} x {metadata['n_bins_L']}")
    
    # Find maximum
    max_idx = np.unravel_index(histogram.argmax(), histogram.shape)
    h_centers = (h_edges[:-1] + h_edges[1:]) / 2
    L_centers = (L_edges[:-1] + L_edges[1:]) / 2
    
    print(f"\nMaximum count: {histogram[max_idx]:,}")
    print(f"  at h = {h_centers[max_idx[0]]:.4f}, L = {L_centers[max_idx[1]]:.4f}")
    
    # Calculate means weighted by counts
    h_marginal = histogram.sum(axis=1)
    L_marginal = histogram.sum(axis=0)
    
    h_mean = np.sum(h_centers * h_marginal) / h_marginal.sum()
    L_mean = np.sum(L_centers * L_marginal) / L_marginal.sum()
    
    print(f"\nWeighted means:")
    print(f"  <h> = {h_mean:.4f}")
    print(f"  <L> = {L_mean:.4f}")
    
    # Check for empty bins
    n_empty = np.sum(histogram == 0)
    total_bins = histogram.size
    print(f"\nEmpty bins: {n_empty} / {total_bins} ({100*n_empty/total_bins:.2f}%)")


