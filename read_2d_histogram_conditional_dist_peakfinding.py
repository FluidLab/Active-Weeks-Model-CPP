def read_2d_histogram(filename):
    """
    Read 2D histogram binary file created by C++ code.
    
    Returns:
        histogram: 2D numpy array of counts (n_bins_h x n_bins_L)
        h_edges: 1D array of h bin edges (length n_bins_h + 1)
        L_edges: 1D array of L bin edges (length n_bins_L + 1)
        metadata: dict with histogram parameters
    """
    with open(filename, 'rb') as f:
        # Read metadata
        n_bins_h = np.fromfile(f, dtype=np.int32, count=1)[0]
        n_bins_L = np.fromfile(f, dtype=np.int32, count=1)[0]
        h_min = np.fromfile(f, dtype=np.float64, count=1)[0]
        h_max = np.fromfile(f, dtype=np.float64, count=1)[0]
        L_min = np.fromfile(f, dtype=np.float64, count=1)[0]
        L_max = np.fromfile(f, dtype=np.float64, count=1)[0]
        
        # Read histogram counts (row-major: h first, then L)
        counts = np.fromfile(f, dtype=np.int64, count=n_bins_h * n_bins_L)
        histogram = counts.reshape((n_bins_h, n_bins_L))
        
        # Create bin edges
        h_edges = np.linspace(h_min, h_max, n_bins_h + 1)
        L_edges = np.linspace(L_min, L_max, n_bins_L + 1)
        
        metadata = {
            'n_bins_h': n_bins_h,
            'n_bins_L': n_bins_L,
            'h_min': h_min,
            'h_max': h_max,
            'L_min': L_min,
            'L_max': L_max,
            'total_counts': histogram.sum()
        }
        
    return histogram, h_edges, L_edges, metadata


def find_peaks_via_conditionals(p_alpha, h_centers, L_centers, 
                                threshold=0.1, conditional_prominence=0.01,
                                min_distance=None):
    """
    Find peaks using a two-stage approach:
    1. Find peaks with relative prominence in each conditional distribution P(h|L)
    2. Retain only those candidates above a global probability threshold

    This approach is robust for ridge-like structures that vary smoothly with L,
    since the prominence threshold adapts to the local scale of each slice.

    Args:
        p_alpha: 2D probability distribution (n_bins_h x n_bins_L)
        h_centers: 1D array of h bin centers
        L_centers: 1D array of L bin centers
        threshold: Minimum relative height for a peak (relative to global max)
        conditional_prominence: Prominence threshold for peak detection in P(h|L),
                                relative to the maximum of that slice
        min_distance: Minimum distance between peaks in a conditional slice (in bins)

    Returns:
        peaks: List of tuples (h_peak, L_peak, value, h_idx, L_idx),
               sorted by probability value descending
    """
    from scipy.signal import find_peaks as find_peaks_1d
    from scipy.ndimage import maximum_filter
    
    global_max = p_alpha.max()
    n_bins_h, n_bins_L = p_alpha.shape
    
    # Stage 1: Find peaks in all conditional distributions P(h|L)
    print(f"Stage 1: Finding peaks in conditional distributions P(h|L)")
    candidate_peaks = []
    
    for L_idx in range(n_bins_L):
        # Extract conditional distribution at this L
        h_conditional = p_alpha[:, L_idx]
        
        # Skip if this slice is too empty
        if h_conditional.sum() < 1e-10:
            continue
        
        # Find peaks in this conditional distribution
        # Scale prominence by the maximum of this conditional slice
        slice_max = h_conditional.max()
        abs_prominence = conditional_prominence * slice_max
        
        peak_indices, properties = find_peaks_1d(
            h_conditional,
            prominence=abs_prominence,
            distance=min_distance
        )
        
        for h_idx in peak_indices:
            prob_val = p_alpha[h_idx, L_idx]
            candidate_peaks.append((h_centers[h_idx], L_centers[L_idx], prob_val, h_idx, L_idx))

    print(f"  Found {len(candidate_peaks)} candidate peaks from conditional distributions")
    
    # Stage 2: Retain only peaks above the global probability threshold
    print("Stage 2: Applying global threshold filter")
    peaks = [(h, L, v, hi, Li) for h, L, v, hi, Li in candidate_peaks
             if v >= threshold * global_max]

    print(f"  Kept {len(peaks)} peaks above threshold = {threshold} * global_max")

    peaks.sort(key=lambda x: x[2], reverse=True)
    return peaks

def find_peaks_2d_old(p_alpha, h_centers, L_centers, 
                                threshold=0.1, radial_threshold=None):
    """
    OLD VERSION: Find local maxima (peaks) in the 2D probability distribution.
    This version finds peaks in full 2D space, not along ridges.
    Kept for backward compatibility.
    
    Args:
        p_alpha: 2D probability distribution (n_bins_h x n_bins_L)
        h_centers: 1D array of h bin centers
        L_centers: 1D array of L bin centers
        threshold: Minimum relative height for a peak (relative to global max)
        radial_threshold: Radial distance defining the neighborhood for peak detection.
                         If None, uses a fixed 3x3 neighborhood.
    
    Returns:
        List of tuples: (h_peak, L_peak, value, h_idx, L_idx)
    """
    from scipy.ndimage import maximum_filter
    
    # Determine neighborhood size based on radial threshold
    if radial_threshold is not None:
        # Calculate bin sizes
        h_bin_size = h_centers[1] - h_centers[0] if len(h_centers) > 1 else 1.0
        L_bin_size = L_centers[1] - L_centers[0] if len(L_centers) > 1 else 1.0
        
        # Convert radial threshold to number of bins (round up to ensure coverage)
        # Use ceiling to be conservative: a radial_threshold should exclude everything within that radius
        neighborhood_h = int(np.ceil(radial_threshold / h_bin_size))
        neighborhood_L = int(np.ceil(radial_threshold / L_bin_size))
        
        # Ensure odd size (required for symmetric neighborhood) and at least 3
        neighborhood_h = max(3, 2 * neighborhood_h + 1)
        neighborhood_L = max(3, 2 * neighborhood_L + 1)
        
        neighborhood_size = (neighborhood_h, neighborhood_L)
        print(f"Using radial threshold {radial_threshold:.3f}: neighborhood size = {neighborhood_size}")
    else:
        # Default fixed 3x3 neighborhood
        neighborhood_size = 3
        print(f"Using default 3x3 neighborhood")
    
    # Find local maxima using maximum filter
    # A point is a local maximum if it equals the maximum in its neighborhood
    local_max = maximum_filter(p_alpha, size=neighborhood_size) == p_alpha
    
    # Apply threshold relative to global maximum
    global_max = p_alpha.max()
    threshold_mask = p_alpha >= threshold * global_max
    
    # Combine conditions
    peaks_mask = local_max & threshold_mask
    
    # Get peak coordinates
    peak_indices = np.argwhere(peaks_mask)
    
    peaks = []
    for h_idx, L_idx in peak_indices:
        h_val = h_centers[h_idx]
        L_val = L_centers[L_idx]
        prob_val = p_alpha[h_idx, L_idx]
        peaks.append((h_val, L_val, prob_val, h_idx, L_idx))
    
    # Sort by probability value (highest first)
    peaks.sort(key=lambda x: x[2], reverse=True)
    
    return peaks


def find_peaks_2d(p_alpha, h_centers, L_centers, threshold=0.1, 
                  ridge_prominence=0.5, peak_prominence=0.02, 
                  min_ridge_length=3, smoothing_sigma=1.5,
                  use_ridge_detection=True, hessian_sigma=2.0,
                  use_log_space=True):
    """
    Find peaks along ridges in a 2D probability distribution.
    
    Strategy:
    1. Detect ridge pixels using the Hessian matrix (eigenvalue analysis)
    2. Extract 1D curves along these ridges
    3. Find peaks along each ridge curve
    
    Args:
        p_alpha: 2D probability distribution (n_bins_h x n_bins_L)
        h_centers: 1D array of h bin centers
        L_centers: 1D array of L bin centers
        threshold: Minimum relative height (relative to global max)
        ridge_prominence: Prominence threshold for ridge detection in log space (absolute)
        peak_prominence: Prominence threshold for peaks along ridges (relative to max)
        min_ridge_length: Minimum number of pixels in a ridge to analyze
        smoothing_sigma: Gaussian smoothing sigma for ridge detection
        use_ridge_detection: If False, fall back to old 2D peak detection
        hessian_sigma: Sigma for Hessian matrix calculation
        use_log_space: If True, detect ridges in log-probability space
        
    Returns:
        peaks: List of tuples: (h_peak, L_peak, value, h_idx, L_idx)
        ridge_mask: 2D boolean array indicating ridge pixels (for visualization)
    """
    if not use_ridge_detection:
        # Fall back to old method
        peaks = find_peaks_2d_old(p_alpha, h_centers, L_centers, threshold=threshold)
        ridge_mask = None
        return peaks, ridge_mask
    
    from scipy.ndimage import gaussian_filter, label
    from scipy.signal import find_peaks as find_peaks_1d
    from skimage.feature import hessian_matrix, hessian_matrix_eigvals
    
    global_max = p_alpha.max()
    
    # Work in log space for ridge detection if requested
    if use_log_space:
        # Add small epsilon to avoid log(0), then take log
        log_p = np.log10(p_alpha + 1e-10)
        # Smooth in log space
        log_p_smooth = gaussian_filter(log_p, sigma=smoothing_sigma)
        
        # Calculate Hessian eigenvalues in log space
        H_elems = hessian_matrix(log_p_smooth, sigma=hessian_sigma, order='rc')
        eigvals = hessian_matrix_eigvals(H_elems)
        
        # Ridge strength: ridges have large negative curvature in one direction
        # Use the smaller (more negative) eigenvalue
        ridge_strength = -np.minimum(eigvals[0], eigvals[1])
        
        print(f"Ridge strength range in log space: [{ridge_strength.min():.3f}, {ridge_strength.max():.3f}]")
        
        # Identify ridge pixels
        # In log space, use absolute threshold for ridge strength
        ridge_mask = (ridge_strength > ridge_prominence) & \
                     (p_alpha > threshold * global_max)
    else:
        # Original approach in probability space
        p_smooth = gaussian_filter(p_alpha, sigma=smoothing_sigma)
        
        H_elems = hessian_matrix(p_smooth, sigma=hessian_sigma, order='rc')
        eigvals = hessian_matrix_eigvals(H_elems)
        
        ridge_strength = -np.minimum(eigvals[0], eigvals[1])
        
        print(f"Ridge strength range in prob space: [{ridge_strength.min():.3e}, {ridge_strength.max():.3e}]")
        
        # Identify ridge pixels
        ridge_mask = (ridge_strength > ridge_prominence * global_max) & \
                     (p_alpha > threshold * global_max)
    
    # Label connected ridge components
    ridge_labels, n_ridges = label(ridge_mask)
    
    print(f"Ridge detection: found {n_ridges} ridge components")
    
    peaks = []
    
    # Process each ridge separately
    for ridge_id in range(1, n_ridges + 1):
        ridge_pixels = np.argwhere(ridge_labels == ridge_id)
        
        if len(ridge_pixels) < min_ridge_length:
            print(f"  Ridge {ridge_id}: {len(ridge_pixels)} pixels (skipped - too short)")
            continue
        
        # Extract values along this ridge (use original probability for peak finding)
        ridge_values = p_alpha[ridge_pixels[:, 0], ridge_pixels[:, 1]]
        
        # Find peaks along this 1D ridge
        # Use scipy.signal.find_peaks for proper 1D peak detection
        peak_indices_1d, properties = find_peaks_1d(
            ridge_values,
            prominence=peak_prominence * global_max,
            distance=3  # Minimum spacing between peaks (in pixels)
        )
        
        print(f"  Ridge {ridge_id}: {len(ridge_pixels)} pixels, {len(peak_indices_1d)} peaks")
        
        # Convert back to 2D coordinates
        for peak_idx_1d in peak_indices_1d:
            h_idx, L_idx = ridge_pixels[peak_idx_1d]
            h_val = h_centers[h_idx]
            L_val = L_centers[L_idx]
            prob_val = p_alpha[h_idx, L_idx]
            peaks.append((h_val, L_val, prob_val, h_idx, L_idx))
    
    # Sort by probability value (highest first)
    peaks.sort(key=lambda x: x[2], reverse=True)
    
    return peaks, ridge_mask


